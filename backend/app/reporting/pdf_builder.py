import io
from typing import Dict, Any
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

def build_pdf_report(data: Dict[str, Any], ai_narrative: str = "") -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()
    
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=20,
        leading=24,
        textColor=colors.HexColor('#1e1b4b'),
        spaceAfter=4
    )
    
    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#64748b'),
        spaceAfter=15
    )

    h2_style = ParagraphStyle(
        'Heading2Custom',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=13,
        leading=17,
        textColor=colors.HexColor('#312e81'),
        spaceBefore=14,
        spaceAfter=6
    )

    body_style = ParagraphStyle(
        'BodyCustom',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=13,
        textColor=colors.HexColor('#1f2937')
    )

    story = []

    # Title & Metadata
    proj_name = data.get("project", {}).get("name", "ML Project")
    story.append(Paragraph(f"AI Experiment Research Report: {proj_name}", title_style))
    now_str = datetime.now().strftime("%B %d, %Y - %H:%M UTC")
    story.append(Paragraph(f"Generated by ML Experiment Orchestrator  |  Date: {now_str}", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#e2e8f0'), spaceAfter=12))

    # Executive Summary
    story.append(Paragraph("1. Executive Summary", h2_style))
    desc = data.get("project", {}).get("description") or "Production Machine Learning experimentation workspace."
    story.append(Paragraph(desc, body_style))
    story.append(Spacer(1, 10))

    # KPI Table
    best = data.get("best_run")
    best_acc = best.get("metrics", {}).get("accuracy") if best else None
    acc_str = f"{best_acc * 100:.2f}%" if isinstance(best_acc, (int, float)) else "N/A"

    kpi_data = [
        ["Total Logged Runs", "Datasets Indexed", "Champion Model", "Top Metric (Accuracy)"],
        [str(data.get("total_runs", 0)), str(len(data.get("datasets", []))), (best.get("name") if best else "N/A")[:20], acc_str]
    ]
    kpi_table = Table(kpi_data, colWidths=[130, 110, 150, 140])
    kpi_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#4f46e5')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 9),
        ('BACKGROUND', (0, 1), (-1, 1), colors.HexColor('#f8fafc')),
        ('TEXTCOLOR', (0, 1), (-1, 1), colors.HexColor('#0f172a')),
        ('FONTNAME', (0, 1), (-1, 1), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 1), (-1, 1), 11),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1'))
    ]))
    story.append(kpi_table)
    story.append(Spacer(1, 14))

    # Runs History Table
    story.append(Paragraph("2. MLflow Experiment Trials & Runs", h2_style))
    runs = data.get("runs", [])
    if runs:
        runs_table_rows = [["Run Name", "Experiment", "Status", "Accuracy"]]
        for r in runs[:10]:
            acc_val = r.get("metrics", {}).get("accuracy")
            acc_display = f"{acc_val:.4f}" if isinstance(acc_val, (int, float)) else "N/A"
            runs_table_rows.append([r.get("name", "")[:24], r.get("experiment_name", "")[:18], r.get("status", "N/A"), acc_display])
        rtable = Table(runs_table_rows, colWidths=[180, 150, 100, 100])
        rtable.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#e0e7ff')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor('#312e81')),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 8),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f8fafc')]),
            ('PADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(rtable)
    else:
        story.append(Paragraph("No runs logged yet.", body_style))
    story.append(Spacer(1, 14))

    # AI Insights
    if ai_narrative:
        story.append(Paragraph("3. AI Data Scientist Insights & Recommendations", h2_style))
        for paragraph in ai_narrative.split("\n"):
            if paragraph.strip():
                story.append(Paragraph(paragraph.strip(), body_style))
                story.append(Spacer(1, 4))

    doc.build(story)
    return buffer.getvalue()
